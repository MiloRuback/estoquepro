CREATE TABLE IF NOT EXISTS public.usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL CHECK (length(trim(nome)) BETWEEN 2 AND 120),
  email text NOT NULL UNIQUE CHECK (email = lower(trim(email))),
  senha_hash text NOT NULL,
  papel text NOT NULL DEFAULT 'OPERADOR' CHECK (papel IN ('ADMIN', 'OPERADOR')),
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz(3) NOT NULL DEFAULT now(),
  atualizado_em timestamptz(3) NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.categorias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL CHECK (length(trim(nome)) BETWEEN 2 AND 80),
  descricao text,
  criado_em timestamptz(3) NOT NULL DEFAULT now(),
  atualizado_em timestamptz(3) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS categorias_nome_lower_uq ON public.categorias (lower(nome));

CREATE TABLE IF NOT EXISTS public.produtos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL CHECK (length(trim(nome)) BETWEEN 2 AND 160),
  descricao text,
  sku text NOT NULL CHECK (length(trim(sku)) BETWEEN 1 AND 40),
  categoria_id integer NOT NULL REFERENCES public.categorias(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  quantidade integer NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
  estoque_minimo integer NOT NULL DEFAULT 0 CHECK (estoque_minimo >= 0),
  preco_custo double precision NOT NULL DEFAULT 0 CHECK (preco_custo >= 0),
  preco_venda double precision NOT NULL DEFAULT 0 CHECK (preco_venda >= 0),
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz(3) NOT NULL DEFAULT now(),
  atualizado_em timestamptz(3) NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS produtos_sku_lower_uq ON public.produtos (lower(sku));
CREATE INDEX IF NOT EXISTS produtos_categoria_idx ON public.produtos (categoria_id);
CREATE INDEX IF NOT EXISTS produtos_nome_idx ON public.produtos (nome);

CREATE TABLE IF NOT EXISTS public.movimentacoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produto_id integer NOT NULL REFERENCES public.produtos(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  tipo text NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA')),
  quantidade integer NOT NULL CHECK (quantidade > 0),
  motivo text,
  observacao text,
  saldo_resultante integer NOT NULL CHECK (saldo_resultante >= 0),
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  criado_em timestamptz(3) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS movimentacoes_produto_idx ON public.movimentacoes (produto_id);
CREATE INDEX IF NOT EXISTS movimentacoes_tipo_idx ON public.movimentacoes (tipo);
CREATE INDEX IF NOT EXISTS movimentacoes_criado_em_idx ON public.movimentacoes (criado_em DESC);

-- O saldo só muda junto com uma movimentação válida. O bloqueio da linha
-- do produto serializa duas saídas concorrentes do mesmo item.
CREATE OR REPLACE FUNCTION public.aplicar_movimentacao_estoque()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  saldo_atual integer;
  produto_ativo boolean;
BEGIN
  IF NEW.quantidade IS NULL OR NEW.quantidade <= 0 THEN
    RAISE EXCEPTION 'A quantidade da movimentação deve ser maior que zero' USING ERRCODE = '23514';
  END IF;

  SELECT quantidade, ativo INTO saldo_atual, produto_ativo
  FROM produtos WHERE id = NEW.produto_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Produto inexistente' USING ERRCODE = '23503';
  END IF;
  IF NOT produto_ativo THEN
    RAISE EXCEPTION 'Produto arquivado não pode receber movimentações' USING ERRCODE = '23514';
  END IF;

  IF NEW.tipo = 'ENTRADA' THEN
    NEW.saldo_resultante := saldo_atual + NEW.quantidade;
  ELSIF NEW.tipo = 'SAIDA' THEN
    IF NEW.quantidade > saldo_atual THEN
      RAISE EXCEPTION 'Estoque insuficiente: disponível %, solicitado %', saldo_atual, NEW.quantidade USING ERRCODE = '23514';
    END IF;
    NEW.saldo_resultante := saldo_atual - NEW.quantidade;
  ELSE
    RAISE EXCEPTION 'Tipo deve ser ENTRADA ou SAIDA' USING ERRCODE = '23514';
  END IF;

  UPDATE produtos
  SET quantidade = NEW.saldo_resultante, atualizado_em = now()
  WHERE id = NEW.produto_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS movimentacoes_atualiza_estoque ON public.movimentacoes;
CREATE TRIGGER movimentacoes_atualiza_estoque
BEFORE INSERT ON public.movimentacoes
FOR EACH ROW EXECUTE FUNCTION public.aplicar_movimentacao_estoque();
